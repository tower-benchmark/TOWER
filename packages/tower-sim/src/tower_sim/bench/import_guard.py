def matched_archive_stems(receipt):
    """Preserve filename and module-alias checks in the shared import validator."""
    stems = {
        stem
        for name, row in receipt["modules"].items()
        for stem in (Path(row["path"]).stem, name.rsplit(".", 1)[-1])
    }
    return {
        stem
        for stem in stems
        if hashlib.sha256(stem.encode("utf-8")).hexdigest() in ARCHIVE_STEM_SHA256
    }
