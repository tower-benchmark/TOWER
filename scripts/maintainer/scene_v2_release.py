"""Stage or recheck the redacted release and all 600 v1/v2 resolution bindings.

No downloads, uploads or frozen writes. --write-metadata is only for preparing a
new revision; routine checks compare regenerated bytes to committed metadata.
"""

import argparse
import hashlib
import json
from pathlib import Path

from tower_sim.bench.public_surface import check_lineage
from tower_sim.bench.scene_format import (
    canonical,
    decode_scene,
    digest,
    encode_scene,
    validate_public,
)

from scripts.maintainer.archive_scene import (
    V1_PREFIX,
    MissingV1Data,
    V1Source,
    assert_runtime_equal,
    lineage,
    public_scene,
)
from scripts.maintainer.archive_scene import (
    manifest as archive_manifest,
)

ROOT = Path(__file__).resolve().parents[2]
REVISION = "2026.11.1"


def bytes_for(value):
    return canonical(value) + b"\n"


def read(path):
    return json.loads(path.read_bytes())


def generate(root, assets, *, v1_root=None, internal_output=None):
    source = V1Source(root, v1_root)
    asset_manifest = read(assets / "manifest.json")
    payloads, table, sidecar = {}, [], []
    pins = archive_manifest()["files"]

    def frozen(name):
        relative = V1_PREFIX + name
        return json.loads(source.read(relative, pins[relative]))

    protocol = frozen("protocol.json")
    for task in protocol["tasks"]:
        rows = frozen("scenes/" + task + ".json")["scenes"]
        encoded = []
        for number, original in enumerate(rows):
            scene_id = f"scene-{number:03d}"
            body = public_scene(original, scene_id)
            validate_public(body)
            assert encode_scene(decode_scene(body)) == body, "schema round trip"
            assert_runtime_equal(original, body, assets, asset_manifest)
            table.append(
                dict(
                    task=task,
                    scene_id=scene_id,
                    old_sha256=digest(original),
                    new_sha256=digest(body),
                    physical_sha256=digest(
                        dict(episode=body["episode"], initial_state=body["initial_state"])
                    ),
                )
            )
            sidecar.append(dict(lineage(original), public_scene_id=scene_id))
            encoded.append(body)
        payloads[f"scenes/{task}.json"] = bytes_for(
            dict(schema="tower-scenes-v2", task=task, scenes=encoded)
        )
    assert len(table) == 600 and len({(r["task"], r["scene_id"]) for r in table}) == 600
    table.sort(key=lambda r: (r["task"], r["scene_id"]))
    sidecar.sort(key=lambda r: r["scene_id"])
    if internal_output is not None:
        internal_output.mkdir(parents=True, exist_ok=False)
        payload = bytes_for(dict(schema="tower-scene-lineage-v1", scenes=sidecar))
        (internal_output / "lineage.json").write_bytes(payload)
        (internal_output / "MANIFEST.json").write_bytes(
            bytes_for(
                dict(
                    schema="tower-internal-lineage-manifest-v1",
                    visibility="internal-only; never upload",
                    files={
                        "lineage.json": dict(
                            sha256=hashlib.sha256(payload).hexdigest(), size=len(payload)
                        )
                    },
                )
            )
        )
    rows = {
        name: dict(sha256=hashlib.sha256(data).hexdigest(), size=len(data))
        for name, data in payloads.items()
    }
    metadata = {
        "protocol.json": protocol,
        "scene-index.json": dict(
            schema="tower-scene-index-v2",
            benchmark=REVISION,
            scenes=[
                {k: r[k] for k in ("task", "scene_id", "new_sha256", "physical_sha256")}
                for r in table
            ],
        ),
        "scene-equivalence.json": dict(
            schema="tower-scene-equivalence-v1",
            old_benchmark="2026.11.0",
            benchmark=REVISION,
            scenes=table,
        ),
        "data-manifest.json": dict(
            schema="tower-benchmark-data-v2", data_version="benchmark-" + REVISION, files=rows
        ),
        "validation.json": dict(
            schema="tower-scene-validation-v1",
            benchmark=REVISION,
            scenes=600,
            lossless_v1_compatibility=True,
            resolved_physical_equality=True,
            schema_round_trip=True,
            gpu_acceptance=False,
            posture_acceptance=False,
        ),
    }
    protocol["guards"].pop("new_pilot_acceptance_requires", None)
    protocol["guards"].pop("reverse_grasp_fallback", None)

    # Only evaluation is public; no generation guidance or campaign labels.
    def neutral(value):
        if isinstance(value, dict):
            return {k: neutral(v) for k, v in value.items()}
        if isinstance(value, list):
            return [neutral(v) for v in value if v != "new scene generation"]
        if isinstance(value, str):
            return value.replace("Isaac Sim 6.1.0-test (campaign build)", "Isaac Sim 6.1.0")
        return value

    metadata["protocol.json"] = neutral(protocol)
    for value in metadata.values():
        validate_public(value)
    return payloads, {k: bytes_for(v) for k, v in metadata.items()}


README = """# Benchmark 2026.11.1 data release

Upload exactly this directory's contents, including MANIFEST.json, to your Hugging Face dataset, preserving relative paths. assets.lock.json is the repository's download locator and is excluded from the upload.

After upload, from the repository root run:

```sh
$EDITOR benchmarks/2026.11.1/assets.lock.json
# Set repository to the dataset name and revision to its exact 40-character commit.
# Keep manifest_sha256 unchanged; directory is the uploaded subdirectory (or .).
python -c "import json; from tower_sim.bench import data_release as d; d.verify_locator(json.load(open('benchmarks/2026.11.1/assets.lock.json')), require_pin=True)"
python -c "import tempfile; from tower_sim.bench import data_release as d; scratch = tempfile.TemporaryDirectory(); d.download('.', scratch.name); print(len(d.verify_release(d.payload_root(scratch.name)))); scratch.cleanup()"
python tools/simulator/benchmark.py verify --assets "$ASSETS" --data-root "$DATA_ROOT"
python -m pytest tests/test_no_internal_leaks.py
```

Set ASSETS to the pinned physical asset release and DATA_ROOT to this directory. The temporary download checks the pinned remote content and removes its local copy. Pinning only the repository/revision/tag/directory locator does not change data identity or invalidate GPU receipts. Do not regenerate the content manifest when pinning.

Local evaluation uses --assets "$ASSETS" --data-root "$DATA_ROOT", or this directory at <assets>/benchmark-2026.11.1. The release includes all 600 evaluation scenes and an old-to-new content hash map.

CPU equality is not GPU or posture acceptance; consult the release acceptance record.
"""


def stage(root, assets, output, *, write_metadata=False, v1_root=None, internal_output=None):
    if internal_output is not None and (
        internal_output.resolve().is_relative_to(output.resolve())
        or output.resolve().is_relative_to(internal_output.resolve())
        or internal_output.resolve().is_relative_to(root.resolve())
    ):
        raise ValueError("Internal lineage must be outside the checkout and public release")
    payloads, metadata = generate(root, assets, v1_root=v1_root, internal_output=internal_output)
    target = root / "benchmarks" / REVISION
    package = root / "packages/tower-sim/src/tower_sim/bench"
    upload = (
        payloads
        | metadata
        | {
            "scene-v2.schema.json": (package / "scene-v2.schema.json").read_bytes(),
            "README.md": README.encode(),
        }
    )
    for name, payload in upload.items():
        check_lineage(name, payload)
    entries = {
        name: dict(sha256=hashlib.sha256(data).hexdigest(), size=len(data))
        for name, data in sorted(upload.items())
    }
    upload_manifest = bytes_for(dict(schema="tower-staged-release-v1", files=entries))
    manifest_hash = hashlib.sha256(upload_manifest).hexdigest()
    lock_path = target / "assets.lock.json"
    lock = dict(
        schema="tower-benchmark-data-lock-v1",
        repository="TODO(owner): HF dataset repository",
        revision="TODO(owner): immutable HF commit",
        tag="benchmark-" + REVISION,
        directory=".",
        manifest_sha256=manifest_hash,
    )
    if lock_path.is_file():
        existing = read(lock_path)
        for key in ("repository", "revision", "tag", "directory"):
            lock[key] = existing[key]
    metadata["assets.lock.json"] = bytes_for(lock)
    for name, data in metadata.items():
        if write_metadata:
            target.mkdir(parents=True, exist_ok=True)
            (target / name).write_bytes(data)
        elif (target / name).read_bytes() != data:
            raise ValueError(f"Committed scene mapping/metadata differs: {name}")
    public = dict(
        data_version="benchmark-" + REVISION,
        protocol=f"benchmarks/{REVISION}/protocol.json",
        scene_index=f"benchmarks/{REVISION}/scene-index.json",
        files={
            f"benchmarks/{REVISION}/{name}": hashlib.sha256(data).hexdigest()
            for name, data in metadata.items()
            if name != "assets.lock.json"
        },
        payload_files=json.loads(metadata["data-manifest.json"])["files"],
        manifest_sha256=manifest_hash,
        upload_files=entries,
    )
    public["files"][f"benchmarks/{REVISION}/assets.lock.json"] = dict(manifest_sha256=manifest_hash)
    if write_metadata:
        (package / "public-data.json").write_text(json.dumps(public, indent=2) + "\n")
    elif read(package / "public-data.json") != public:
        raise ValueError("Package data-manifest binding differs")
    output.mkdir(parents=True, exist_ok=False)
    for name, data in upload.items():
        path = output / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    (output / "MANIFEST.json").write_bytes(upload_manifest)
    return dict(
        scenes=600,
        passed=True,
        payload_files=len(payloads),
        payload_bytes=sum(map(len, payloads.values())),
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--write-metadata", action="store_true")
    parser.add_argument(
        "--internal-output",
        type=Path,
        help="Private lineage destination outside the public release and checkout",
    )
    parser.add_argument(
        "--v1-root", "--archive-root", type=Path, help="Explicit private archive export"
    )
    parser.add_argument(
        "--allow-skip",
        action="store_true",
        help="Allow missing archive evidence (still reported as skipped)",
    )
    args = parser.parse_args()
    try:
        result = stage(
            ROOT,
            args.assets.resolve(),
            args.output.resolve(),
            write_metadata=args.write_metadata,
            v1_root=args.v1_root,
            internal_output=args.internal_output,
        )
    except ValueError as error:
        parser.error(str(error))
    except MissingV1Data as error:
        if args.v1_root is not None:
            parser.error(str(error))
        result = dict(passed=False, skipped=True, reason=str(error))
    print(json.dumps(result))
    return 77 if result.get("skipped") and not args.allow_skip else 0


if __name__ == "__main__":
    raise SystemExit(main())
